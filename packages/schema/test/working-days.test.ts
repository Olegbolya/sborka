import { describe, expect, it } from 'vitest';
import { addWorkingDays, isWorkingDay } from '../src/index.js';

const at = (iso: string): Date => new Date(`${iso}T07:00:00Z`); // 10:00 по Москве

describe('P8.5 · производственный календарь', () => {
  it('P8.5 · праздники и перенесённые выходные не считаются рабочими днями, перенесённая рабочая суббота считается', () => {
    for (const d of ['2026-01-09', '2026-03-09', '2026-05-11', '2026-11-04', '2026-12-31', '2027-02-22', '2027-06-14', '2027-11-05']) expect(isWorkingDay(at(d)), d).toBe(false);
    for (const d of ['2026-11-03', '2026-11-05', '2027-01-11', '2027-02-20']) expect(isWorkingDay(at(d)), d).toBe(true);
    expect(isWorkingDay(at('2027-02-27'))).toBe(false);
  });

  it('P8.5 · срок в десять рабочих дней пропускает 4 ноября и считает границу суток по Москве', () => {
    // Понедельник 2 ноября 2026 → 3, 5, 6, 9, 10, 11, 12, 13, 16, 17 ноября: десятый рабочий день — 17-е.
    expect(addWorkingDays(at('2026-11-02'), 10).toISOString()).toBe('2026-11-17T07:00:00.000Z');
    // Четверг 24 декабря 2026 → 25, 28, 29, 30 декабря, затем каникулы до 10 января, 11 января — пятый.
    expect(addWorkingDays(at('2026-12-24'), 5).toISOString()).toBe('2027-01-11T07:00:00.000Z');
    // Пятница 19 февраля 2027: суббота 20 февраля рабочая → первый рабочий день — она.
    expect(addWorkingDays(at('2027-02-19'), 1).toISOString()).toBe('2027-02-20T07:00:00.000Z');
    // Год без данных: только суббота и воскресенье.
    expect(addWorkingDays(at('2030-05-03'), 1).toISOString()).toBe('2030-05-06T07:00:00.000Z');
  });
});
